# Writes ios/unicase_table.inc: Unicode full case folding (CaseFolding.txt's C and F mappings, as
# Python's str.casefold applies them), for unicase_compare.c, adjusted to what Anki's collation
# (the `unicase` Rust crate in Anki 26.09) actually does, measured with Anki's own code by sorting
# every code point (tests/anki/sync/unicase.test.ts checks the result against that ordering):
# - A character that folds to three is compared with those three last-first (ﬃ sorts as "iff").
# - Case pairs added in Unicode 14 and later (Vithkuqi, some Latin) aren't folded at all.
#   python3 modules/anki-unicase/make-table.py
import os, sys, unicodedata

# Code points Anki's collation leaves as they are, though Python folds them (newer Unicode data).
ANKI_UNFOLDED = {int(h, 16) for h in '''
  2c2f a7c0 a7c7 a7c9 a7d0 a7d6 a7d8 a7f5 10570 10571 10572 10573 10574 10575 10576 10577 10578
  10579 1057a 1057c 1057d 1057e 1057f 10580 10581 10582 10583 10584 10585 10586 10587 10588 10589
  1058a 1058c 1058d 1058e 1058f 10590 10591 10592 10594 10595
'''.split()}

rows = []
for cp in range(0x110000):
    if cp in ANKI_UNFOLDED:
        continue
    if 0xD800 <= cp <= 0xDFFF:
        continue
    folded = chr(cp).casefold()
    if folded != chr(cp):
        cps = [ord(c) for c in folded]
        assert len(cps) <= 3
        if len(cps) == 3:
            cps.reverse()
        rows.append((cp, cps + [0] * (3 - len(cps))))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'ios', 'unicase_table.inc')
with open(out, 'w') as f:
    f.write('// Generated by make-table.py from Unicode %s case folding. Do not edit.\n' % unicodedata.unidata_version)
    f.write('// Each row: a code point, then the one to three it folds to (0 for none).\n')
    f.write('static const unsigned int UNICASE_FOLDS[][4] = {\n')
    for cp, t in rows:
        f.write('  {0x%x, 0x%x, 0x%x, 0x%x},\n' % (cp, t[0], t[1], t[2]))
    f.write('};\n')
    f.write('#define UNICASE_FOLD_COUNT %d\n' % len(rows))
print(len(rows), 'mappings, Unicode', unicodedata.unidata_version, file=sys.stderr)
