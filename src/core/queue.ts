import { nextStudyDayStart } from './day';
import type { Card, DeckParams } from './types';

export interface QueueOptions {
  newPerDay: number;
  /** New cards already introduced this study day (counts against newPerDay). */
  newIntroducedToday?: number;
  /** Review-state cards shown per study day. Learning cards aren't limited, as in Anki. */
  reviewsPerDay?: number;
  /** Review-state cards already answered this study day (counts against reviewsPerDay). */
  reviewedToday?: number;
  /** The hour the study day starts (`DAY_STARTS_AT_HOUR`). */
  dayStartsAtHour: number;
  /** Show learning cards up to this many minutes early once nothing else is left (`LEARN_AHEAD_MINUTES`). */
  learnAheadMinutes?: number;
  now?: Date;
}

export interface Queue {
  due: Card[];
  fresh: Card[];
}

/**
 * Whether a card that has been studied is due now.
 *
 * A Review card is due for its whole study day, as in Anki: its due instant carries the time of
 * day it was last answered, so read as an instant, a card answered at 9 PM yesterday with a
 * one-day interval would stay hidden until 9 PM today. A Learning or Relearning card is due at
 * its exact instant, since its steps are minutes apart.
 */
export function isDue(card: Card, now: Date, dayStartsAtHour: number): boolean {
  if (card.sched.state === 0) return false;
  const due = new Date(card.sched.due).getTime();
  if (card.sched.state === 2) return due < nextStudyDayStart(now, dayStartsAtHour).getTime();
  return due <= now.getTime();
}

const isLearning = (c: Card) => c.sched.state === 1 || c.sched.state === 3;
const dueMs = (c: Card) => new Date(c.sched.due).getTime();

/** Cards that can be studied at all: not suspended in Anki, and still generated by their note. */
function studiable(cards: Card[]): Card[] {
  return cards.filter((c) => !c.suspended && !c.retired);
}

/**
 * Due reviews/learning first (most overdue first), then up to the daily limit of new cards.
 * Once both are empty, learning cards due within the learn-ahead limit, soonest first.
 *
 * The deck list's counts come from this too (`summarizeDecks`), so what a deck says it has
 * waiting is what opening it shows.
 */
export function buildQueue(cards: Card[], opts: QueueOptions): Queue {
  const now = opts.now ?? new Date();
  const active = studiable(cards);
  let due = active
    .filter((c) => isDue(c, now, opts.dayStartsAtHour))
    .sort((a, b) => dueMs(a) - dueMs(b));
  if (opts.reviewsPerDay !== undefined) {
    // The most overdue reviews fill the day's budget; learning cards pass regardless.
    let reviewBudget = Math.max(0, opts.reviewsPerDay - (opts.reviewedToday ?? 0));
    due = due.filter((c) => c.sched.state !== 2 || reviewBudget-- > 0);
  }
  const budget = Math.max(0, opts.newPerDay - (opts.newIntroducedToday ?? 0));
  const fresh = active.filter((c) => c.sched.state === 0).slice(0, budget);
  if (due.length === 0 && fresh.length === 0 && opts.learnAheadMinutes) {
    const cutoff = now.getTime() + opts.learnAheadMinutes * 60000;
    due = active.filter((c) => isLearning(c) && dueMs(c) <= cutoff).sort((a, b) => dueMs(a) - dueMs(b));
  }
  return { due, fresh };
}

/**
 * When the next learning card comes due, for a session that has run out of cards: the review
 * screen waits for it instead of declaring the deck done. Undefined when none is waiting.
 */
export function nextLearningDue(cards: Card[]): Date | undefined {
  let best: number | undefined;
  for (const c of studiable(cards)) {
    if (isLearning(c) && (best === undefined || dueMs(c) < best)) best = dueMs(c);
  }
  return best === undefined ? undefined : new Date(best);
}

export function nextCard(q: Queue): Card | undefined {
  return q.due[0] ?? q.fresh[0];
}

/** What a deck has already used of today's limits. */
export interface StudiedToday {
  /** New cards answered for the first time. */
  introduced: number;
  /** Answers given to cards in the Review state. */
  reviewed: number;
}

/**
 * The queue options for a deck: its own limits from its Anki preset when it has them, else the
 * app's defaults. The deck list and the review screen both build their queue through this.
 */
export function queueOptionsFor(
  params: DeckParams | undefined,
  studied: StudiedToday,
  base: { defaultNewPerDay: number; defaultReviewsPerDay: number; dayStartsAtHour: number; learnAheadMinutes?: number; now?: Date },
): QueueOptions {
  return {
    newPerDay: params?.newPerDay ?? base.defaultNewPerDay,
    reviewsPerDay: params?.reviewsPerDay ?? base.defaultReviewsPerDay,
    newIntroducedToday: studied.introduced,
    reviewedToday: studied.reviewed,
    dayStartsAtHour: base.dayStartsAtHour,
    learnAheadMinutes: base.learnAheadMinutes,
    now: base.now,
  };
}
