import { nextStudyDayStart, studyDayKey, studyDayStart } from './day';
import { answersFrom, type RevlogRow } from './stats';
import type { BurySettings, Card, Note, ReviewLogEntry } from './types';

export interface QueueOptions {
  /** The hour the study day starts (`DAY_STARTS_AT_HOUR`). */
  dayStartsAtHour: number;
  now?: Date;
}

export interface Queue {
  /** Cards due: learning (including within the learn-ahead limit) and reviews. */
  due: Card[];
  /** New cards. */
  fresh: Card[];
  /** All of them, in the order they come up (`treeQueue`). */
  order: Card[];
}

/**
 * Whether a card that has been studied is due now.
 *
 * A Review card is due for its whole study day, as in Anki: its due instant carries the time of
 * day it was last answered, so read as an instant, a card answered at 9 PM yesterday with a
 * one-day interval would stay hidden until 9 PM today. A Learning or Relearning card is due at
 * its exact instant, since its steps are minutes apart.
 */
export function isDue(card: Card, now: Date, dayStartsAtHour: number): boolean {
  if (card.sched.state === 0) return false;
  const due = new Date(card.sched.due).getTime();
  if (card.sched.state === 2) return due < nextStudyDayStart(now, dayStartsAtHour).getTime();
  return due <= now.getTime();
}

export const isLearning = (c: Card) => c.sched.state === 1 || c.sched.state === 3;

/** A learning card on a step of a day or more (Anki's queue 3): it's due on a later study day than its last answer. */
export function isInterdayLearning(card: Card, dayStartsAtHour: number): boolean {
  if (!isLearning(card) || !card.sched.lastReview) return false;
  return studyDayKey(new Date(card.sched.due), dayStartsAtHour) > studyDayKey(new Date(card.sched.lastReview), dayStartsAtHour);
}

/**
 * What answering `card` uses of today's limits, as Anki counts it: a new card's first answer is a
 * new card studied, and an answer to a review or a day-long learning card (Anki's queues 2 and 3)
 * is a review. Learning steps within the day use nothing.
 */
export function studiedKind(card: Card, dayStartsAtHour: number): 'new' | 'review' | null {
  if (card.sched.state === 0) return 'new';
  if (card.sched.state === 2 || isInterdayLearning(card, dayStartsAtHour)) return 'review';
  return null;
}
const dueMs = (c: Card) => new Date(c.sched.due).getTime();

/**
 * The siblings (other cards of the note) to hold back until the next study day once `answered` is
 * answered, by its own deck's preset, as Anki's scheduler buries them (rslib's
 * siblings_for_bury.sql): new siblings with "Bury new siblings", review siblings due today with
 * "Bury review siblings", and learning siblings on a step of a day or more and due today with
 * "Bury interday learning siblings". A learning step within the day is never buried.
 */
export function siblingsToBury(answered: Card, cards: Card[], bury: BurySettings | undefined, now: Date, dayStartsAtHour: number): Card[] {
  if (!bury) return [];
  const end = nextStudyDayStart(now, dayStartsAtHour).getTime();
  const dayOf = (iso: string) => studyDayStart(new Date(iso), dayStartsAtHour).getTime();
  return cards.filter((c) => {
    if (c.noteId !== answered.noteId || c.id === answered.id || c.suspended || c.retired || isBuried(c, now, dayStartsAtHour)) return false;
    if (c.sched.state === 0) return bury.new;
    if (dueMs(c) >= end) return false;
    if (c.sched.state === 2) return bury.reviews;
    const interday = !!c.sched.lastReview && dayOf(c.sched.due) > dayOf(c.sched.lastReview);
    return bury.interdayLearning && interday;
  });
}

/** Cards that can be studied at all: not suspended in Anki, and still generated by their note. */
export function studiable(cards: Card[]): Card[] {
  return cards.filter((c) => !c.suspended && !c.retired);
}

/**
 * Whether Anki has the card buried for today: held back until the next study day. Anki unburies
 * every card when a new day starts, on whichever device opens first, so a card buried before
 * today's study day began is studied as usual here without waiting for that device to sync.
 */
export function isBuried(card: Card, now: Date, dayStartsAtHour: number): boolean {
  return !!card.buriedAt && new Date(card.buriedAt).getTime() >= studyDayStart(now, dayStartsAtHour).getTime();
}

/**
 * When the next learning card comes due, for a session that has run out of cards: the review
 * screen waits for it instead of declaring the deck done. Undefined when none is waiting.
 * Only a step within today counts: a day-long step (Anki's queue 3) comes back on its own day,
 * under the review limit, so the session is done rather than waiting for it, as in Anki.
 */
export function nextLearningDue(cards: Card[], opts: QueueOptions): Date | undefined {
  const now = opts.now ?? new Date();
  const dayEnd = nextStudyDayStart(now, opts.dayStartsAtHour).getTime();
  let best: number | undefined;
  for (const c of studiable(cards)) {
    if (isBuried(c, now, opts.dayStartsAtHour)) continue;
    if (!isLearning(c) || isInterdayLearning(c, opts.dayStartsAtHour) || dueMs(c) >= dayEnd) continue;
    if (best === undefined || dueMs(c) < best) best = dueMs(c);
  }
  return best === undefined ? undefined : new Date(best);
}

export function nextCard(q: Queue): Card | undefined {
  return q.order[0];
}

/** What a deck has already used of today's limits. */
export interface StudiedToday {
  /** New cards answered for the first time. */
  introduced: number;
  /** Answers given to cards in the Review state. */
  reviewed: number;
}

/**
 * What each deck has used of today's limits, by its own cards (a parent deck's entry leaves out
 * its subdecks'; `treeQueue` adds them up), from every answer given today on any device. Answers
 * come as `answersFrom` (stats.ts) reads them: the kept collection's review log for Anki's cards,
 * which holds answers synced from AnkiMobile and Anki and Franki's own (write-back puts them
 * there), and Franki's reviews table for the rest. Counting only Franki's table offered new cards
 * already studied in Anki that day. Pass `reviews` and `revlog` from the start of the study day.
 */
export function studiedToday(input: {
  notes: Note[]; cards: Card[]; reviews: ReviewLogEntry[]; revlog: RevlogRow[]; now: Date; dayStartsAtHour: number;
}): Map<string, StudiedToday> {
  const start = studyDayStart(input.now, input.dayStartsAtHour).getTime();
  const deckOfNote = new Map(input.notes.map((n) => [n.id, n.deck]));
  // The deck each card is studied in (deckTree.ts's cardDeck): an answer in a filtered deck counts there, as in Anki.
  const deckOf = new Map(input.cards.map((c) => [c.id, c.filteredDeck ?? c.deck ?? deckOfNote.get(c.noteId)]));
  const introduced = new Map<string, Set<string>>();
  const out = new Map<string, StudiedToday>();
  for (const a of answersFrom(input)) {
    if (a.at.getTime() < start) continue;
    // A preview uses no limits, as in Anki, and its card is back home by now: counted by where it
    // is, 50 previews took 50 off the home deck's review room.
    if (a.preview) continue;
    const deck = deckOf.get(a.cardId);
    if (!deck) continue;
    const s = out.get(deck) ?? { introduced: 0, reviewed: 0 };
    if (a.wasNew) {
      const seen = introduced.get(deck) ?? new Set<string>();
      seen.add(a.cardId);
      introduced.set(deck, seen);
      s.introduced = seen.size;
    } else if (a.kind === 'review' || a.interday) {
      // A review, or an answer to a learning card on a day-long step (Anki's queue 3).
      s.reviewed++;
    } else {
      continue;
    }
    out.set(deck, s);
  }
  return out;
}
